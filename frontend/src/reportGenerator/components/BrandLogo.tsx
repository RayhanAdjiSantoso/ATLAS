export function BrandLogo({ name, size = 20 }: { name: BrandKey; size?: number }) {
  const id = useId().replace(/:/g, '');
  const common = { width: size, height: size, viewBox: '0 0 24 24', 'aria-hidden': true } as const;
  if (name === 'meta') {
    return (
      <svg {...common}>
        <defs>
          <linearGradient id={`meta-${id}`} x1="0" y1="1" x2="1" y2="0">
            <stop offset="0" stopColor="#0064E1" />
            <stop offset=".6" stopColor="#0082FB" />
            <stop offset="1" stopColor="#0099FF" />
          </linearGradient>
        </defs>
        <path d={META} fill={`url(#meta-${id})`} />
      </svg>
    );
  }
  if (name === 'shopee') {
    return (
      <svg {...common}>
        <path d={SHOPEE} fill="#EE4D2D" />
      </svg>
    );
  }
  if (name === 'tiktok') {
    // The note's cyan and red echoes sit behind the black, as in the mark.
    return (
      <svg {...common}>
        <path d={TIKTOK} fill="#25F4EE" transform="translate(-.7 -.6)" />
        <path d={TIKTOK} fill="#FE2C55" transform="translate(.7 .6)" />
        <path d={TIKTOK} fill="#111111" />
      </svg>
    );
  }
  return (
    <svg {...common}>
      <path d={GADS_LEG} fill="#FBBC04" />
      <path d={GADS_BAR} fill="#4285F4" />
      <path d={GADS_DOT} fill="#34A853" />
    </svg>
  );
}
